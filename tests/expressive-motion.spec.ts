import {test,expect} from '@playwright/test'
test.beforeEach(async({page})=>{await page.goto('/#motion')})
test('text replay, number retargeting, spotlight and marquee remain operable with reduced motion',async({page})=>{
 await page.getByRole('button',{name:'重播文字动画'}).click();await expect(page.locator('.ui-text-reveal')).toContainText('让细节自然出现。')
 await page.getByRole('combobox',{name:'文字动画'}).selectOption('rise');await page.getByRole('button',{name:'重播文字动画'}).click()
 await page.getByRole('button',{name:'增加示例数值'}).click();await page.getByRole('button',{name:'增加示例数值'}).click()
 await expect(page.getByRole('img',{name:'示例数值1,757.00'})).toHaveText('1,757.00')
 await page.getByRole('button',{name:'还原示例数值'}).click();await expect(page.getByRole('img',{name:'示例数值1,280.00'})).toHaveText('1,280.00')
 const spot=page.getByRole('region',{name:'光斑预览'});await spot.hover();await expect(spot).toBeVisible()
 await page.getByRole('button',{name:'打开光斑示例详情'}).click();await expect(page.getByRole('dialog')).toBeVisible();await page.keyboard.press('Escape')
 await page.getByRole('button',{name:'播放流动内容'}).click()
 const track=page.locator('.ui-marquee-track');await expect(track).toHaveCSS('animation-play-state','running')
 const before=await track.evaluate(e=>getComputedStyle(e).transform)
 await expect.poll(()=>track.evaluate(e=>getComputedStyle(e).transform)).not.toBe(before)
 await page.getByRole('button',{name:'暂停流动内容'}).click()
 await expect(page.locator('.ui-marquee')).toHaveAttribute('data-paused','true')
 await page.emulateMedia({reducedMotion:'reduce'});await expect(page.getByRole('button',{name:'已减少动态'})).toBeDisabled()
 await page.getByRole('button',{name:'增加示例数值'}).click();await expect(page.getByRole('img',{name:'示例数值1,518.50'})).toHaveText('1,518.50')
 await expect(page.locator('.ui-text-segment').first()).toHaveCSS('animation-name','none')
})
test('page changes preserve the draft under rapid navigation',async({page})=>{
 await page.getByRole('textbox',{name:'页面草稿'}).fill('跨页面仍保留')
 await page.getByRole('button',{name:'预览页',exact:true}).click();await expect(page.getByRole('region',{name:'页面预览'})).toContainText('跨页面仍保留')
 await page.getByRole('button',{name:'返回继续编辑'}).click();await expect(page.getByRole('textbox',{name:'页面草稿'})).toHaveValue('跨页面仍保留')
 for(let i=0;i<3;i++){await page.getByRole('button',{name:'预览页',exact:true}).click();await page.getByRole('button',{name:'编辑页',exact:true}).click()}
 await expect(page.getByRole('textbox',{name:'页面草稿'})).toHaveValue('跨页面仍保留')
})
test('waiting cancels, retries and retains previous content during failed refresh',async({page})=>{
 await page.getByRole('button',{name:'开始演示加载'}).click();await expect(page.getByRole('progressbar',{name:'演示内容加载进度'})).not.toHaveAttribute('aria-valuenow',/./)
 await page.getByRole('button',{name:'取消等待'}).click();await expect(page.getByText('已取消，可重新开始。')).toBeVisible()
 await page.getByRole('button',{name:'重试加载'}).click();await expect(page.locator('.motion-result')).toContainText('已完成 1 次演示加载')
 await page.getByRole('button',{name:'演示失败',exact:true}).click();await expect(page.locator('.motion-result')).toContainText('已完成 1 次演示加载')
 await expect(page.getByText('加载未完成，可重试。')).toBeVisible();await page.getByRole('button',{name:'重试加载'}).click();await expect(page.locator('.motion-result')).toContainText('已完成 2 次演示加载')
})
